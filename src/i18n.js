const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function formatDigits(num, lang) {
  const padded = String(Math.max(0, num)).padStart(2, '0');
  if (lang === 'en') return padded;
  return padded.replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
}

const HTML_KEYS = new Set(['s11.s1Date', 's11.s2Date', 's14.credit']);

export function applyLanguage(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.bn;
  document.documentElement.dataset.lang = lang;
  document.documentElement.lang = lang === 'en' ? 'en' : 'bn';

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const val = dict[key];
    if (val === undefined) return;
    if (HTML_KEYS.has(key)) {
      el.innerHTML = val;
    } else {
      el.textContent = val;
    }
  });
}
